"""Generates, from sheets/combat.json: the 7 Days XML patch with Minecraft swing rates
(SteveDaysToDie/Config/items.xml) and the code table (src/Generated/CombatTable.cs).
Covers EVERY melee item a player can hold: exact rows first, then the class rules."""
import json, os, re
from gamedata import ROOT, SevenDays

sheet = json.load(open(os.path.join(ROOT, "sheets", "combat.json"), encoding="utf-8"))
exact = {r["id_7days"]: r["attack_speed"] for r in sheet["rows"]}
classes = [(re.compile(c["match"]), c) for c in sheet["classes"]]
sd = SevenDays()


def action0(name):
    for n in sd.chain(name):
        for p in n.findall("property"):
            if p.get("class") == "Action0":
                for q in p.findall("property"):
                    if q.get("name") == "Class":
                        return q.get("value")
    return None


def player_melee():
    for name in sorted(sd.items):
        node = sd.items[name]
        if node.tag != "item" or name.endswith("Master") or name.endswith("Admin") or name.startswith("admin"):
            continue
        if name.startswith("meleeHand") and name != "meleeHandPlayer":
            continue   # animals' and zombies' attacks
        if action0(name) in ("Melee", "DynamicMelee"):
            yield name


for r in sheet["rows"]:
    if r["id_7days"] not in sd.items:
        raise SystemExit("combat.json: %s no existe en items.xml" % r["id_7days"])

result, unmatched = [], []
for name in player_melee():
    if name in exact:
        result.append((name, exact[name], "par exacto"))
        continue
    cls = next((c for rx, c in classes if rx.search(name)), None)
    if cls is None:
        unmatched.append(name)
    else:
        result.append((name, cls["attack_speed"], cls["class"]))
if unmatched:
    raise SystemExit("combat.json: sin ritmo (agrega una clase): " + ", ".join(unmatched))

xml = ["<configs>", "    <!-- GENERATED by tools/build_config.py from sheets/combat.json: Minecraft swing rates. -->"]
cs = ["// GENERATED by tools/build_config.py from sheets/combat.json. Do not edit by hand.",
      "using System.Collections.Generic;", "", "namespace SteveDaysToDie.Generated", "{",
      "    public static class CombatTable", "    {",
      "        /// <summary>7 Days item name -> seconds for the attack bar to refill (1 / Minecraft attack speed).</summary>",
      "        public static readonly Dictionary<string, float> Cooldown = new Dictionary<string, float>", "        {"]
for name, speed, why in result:
    apm = int(round(speed * 60))
    node = sd.items[name]
    if any(pe.get("name") == "AttacksPerMinute" for pe in node.iter("passive_effect")):
        xml.append("    <set xpath=\"/items/item[@name='%s']/effect_group/passive_effect[@name='AttacksPerMinute']/@value\">%d</set>"
                   % (name, apm))
    else:
        xml.append("    <append xpath=\"/items/item[@name='%s']\"><effect_group name=\"svd_mc_speed\">"
                   "<passive_effect name=\"AttacksPerMinute\" operation=\"base_set\" value=\"%d\"/></effect_group></append>"
                   % (name, apm))
    cs.append("            { \"%s\", %sf },   // %s, %s/s" % (name, round(1.0 / speed, 3), why, speed))
xml.append("</configs>")
cs += ["        };", "    }", "}", ""]
open(os.path.join(ROOT, "SteveDaysToDie", "Config", "items.xml"), "w", encoding="utf-8").write("\n".join(xml) + "\n")
os.makedirs(os.path.join(ROOT, "src", "Generated"), exist_ok=True)
open(os.path.join(ROOT, "src", "Generated", "CombatTable.cs"), "w", encoding="utf-8").write("\n".join(cs))
# ---- survival.json -> src/Generated/SurvivalTable.cs (one constant per row) ----
surv = json.load(open(os.path.join(ROOT, "sheets", "survival.json"), encoding="utf-8"))["rows"]
sc = ["// GENERATED by tools/build_config.py from sheets/survival.json. Do not edit by hand.",
      "namespace SteveDaysToDie.Generated", "{", "    public static class SurvivalTable", "    {"]
for r in surv:
    const = "".join(w.capitalize() for w in r["id"].split("_"))
    sc.append("        /// <summary>%s (%s)</summary>" % (r["rule"], r["unit"]))
    sc.append("        public const float %s = %sf;" % (const, r["value"]))
sc += ["    }", "}", ""]
open(os.path.join(ROOT, "src", "Generated", "SurvivalTable.cs"), "w", encoding="utf-8").write("\n".join(sc))
print("survival rules:", len(surv))

# ---- blocked_buffs.json -> src/Generated/BlockedBuffs.cs ----
bbj = json.load(open(os.path.join(ROOT, "sheets", "blocked_buffs.json"), encoding="utf-8"))
bb, groups = bbj["rows"], bbj["groups"]
gnames = [g["group"] for g in groups]
for r in bb:
    if r["id_7days_buff"] not in sd.buffs:
        raise SystemExit("blocked_buffs.json: %s no existe en buffs.xml" % r["id_7days_buff"])
    if r["group"] not in gnames:
        raise SystemExit("blocked_buffs.json: grupo %s no esta en groups" % r["group"])
q = lambda xs: ", ".join('"%s"' % x for x in xs)
bc = ["// GENERATED by tools/build_config.py from sheets/blocked_buffs.json. Do not edit by hand.",
      "namespace SteveDaysToDie.Generated", "{", "    public static class BlockedBuffs", "    {",
      "        public sealed class Group { public string Setting, Default, Label; public string[] Exact, Prefixes; }",
      "        public static readonly Group[] Groups =", "        {"]
total = 0
for g in groups:
    rows = [r for r in bb if r["group"] == g["group"]]
    exact = sorted({r["id_7days_buff"] for r in rows})
    prefixes = sorted({r["prefix"] for r in rows if r["prefix"] not in ("", "-")})
    covered = sorted(b for b in sd.buffs if b in exact or any(b.startswith(p) for p in prefixes))
    total += len(covered)
    bc.append("            // %s: %s" % (g["group"], ", ".join(covered)))
    bc.append('            new Group { Setting = "efecto_%s", Default = "%s", Label = "%s", Exact = new[] { %s }, Prefixes = new string[] { %s } },'
              % (g["group"], g["default"], g["label"], q(exact), q(prefixes)))
bc += ["        };", "    }", "}", ""]
open(os.path.join(ROOT, "src", "Generated", "BlockedBuffs.cs"), "w", encoding="utf-8").write("\n".join(bc))
print("7 Days effect groups:", len(groups), "effects:", total)

# ---- harvest_tiers.json -> src/Generated/HarvestTable.cs (Minecraft pickaxe levels) ----
import re as _re
import xml.etree.ElementTree as _ET
from gamedata import CFG as _CFG
ht = json.load(open(os.path.join(ROOT, "sheets", "harvest_tiers.json"), encoding="utf-8"))
_mats = {m.get("id") for m in _ET.parse(os.path.join(_CFG, "materials.xml")).getroot().iter("material")}
try:
    from gamedata import Minecraft as _MC
    _mcb = _MC().blocks
except Exception:
    _mcb = None
for r in ht["blocks"]:
    hits = (r["block"] and [b for b in sd.blocks if _re.search(r["block"], b)]) or []
    mhits = (r["material"] and [m for m in _mats if _re.search(r["material"], m)]) or []
    if not hits and not mhits:
        raise SystemExit("harvest_tiers.json: %s no coincide con ningun bloque ni material de 7 Days" % r["key"])
    if _mcb is not None and r["minecraft"] not in _mcb:
        raise SystemExit("harvest_tiers.json: %s -> %s no existe en tu Minecraft" % (r["key"], r["minecraft"]))
    if not 0 <= r["min_tier"] <= 4:
        raise SystemExit("harvest_tiers.json: %s nivel fuera de 0-4" % r["key"])
for t in ht["tools"]:
    if not 0 <= t["tier"] <= 4:
        raise SystemExit("harvest_tiers.json: herramienta %s nivel fuera de 0-4" % t["key"])
esc = lambda s: s.replace("\\", "\\\\").replace('"', '\\"')
hc = ["// GENERATED by tools/build_config.py from sheets/harvest_tiers.json. Do not edit by hand.",
      "namespace SteveDaysToDie.Generated", "{", "    public static class HarvestTable", "    {",
      "        public const float SpeedWithoutTier = %sf;" % ht["speed_without_tier"],
      "        // key, 7 Days block-name pattern, block-material pattern, Minecraft block, minimum pickaxe level",
      "        public static readonly (string key, string block, string material, string minecraft, int minTier)[] Blocks =", "        {"]
for r in ht["blocks"]:
    hc.append('            ("%s", "%s", "%s", "%s", %d),' % (r["key"], esc(r["block"]), esc(r["material"]), r["minecraft"], r["min_tier"]))
hc += ["        };", "        // item-name pattern (7 Days item, or its Minecraft pair), pickaxe level",
       "        public static readonly (string item, int tier)[] Tools =", "        {"]
for t in ht["tools"]:
    hc.append('            ("%s", %d),' % (esc(t["item"]), t["tier"]))
hc += ["        };", "    }", "}", ""]
open(os.path.join(ROOT, "src", "Generated", "HarvestTable.cs"), "w", encoding="utf-8").write("\n".join(hc))
print("harvest tiers:", len(ht["blocks"]), "rocks,", len(ht["tools"]), "pickaxes")

# ---- the jump: survival.json -> SteveDaysToDie/Config/entityclasses.xml ----
jump = next(r["value"] for r in surv if r["id"] == "jump_strength_7days")
ec = ["<configs>",
      "    <!-- GENERATED by tools/build_config.py from sheets/survival.json: Minecraft's jump height (1.25 blocks). -->",
      "    <set xpath=\"/entity_classes/entity_class[@name='playerMale']//passive_effect[@name='JumpStrength' and @value='0.16']/@value\">%s</set>" % jump,
      "    <set xpath=\"/entity_classes/entity_class[@name='playerMale']//passive_effect[@name='JumpStrength' and @tags='crouching']/@value\">%s</set>" % jump,
      "</configs>", ""]
open(os.path.join(ROOT, "SteveDaysToDie", "Config", "entityclasses.xml"), "w", encoding="utf-8").write("\n".join(ec))
print("jump strength:", jump)

# ---- pairs.json -> src/Generated/PairsTable.cs (7 Days id -> its Minecraft pair) ----
pairs = json.load(open(os.path.join(ROOT, "sheets", "pairs.json"), encoding="utf-8"))["pairs"]
pc = ["// GENERATED by tools/build_config.py from sheets/pairs.json. Do not edit by hand.",
      "using System.Collections.Generic;", "", "namespace SteveDaysToDie.Generated", "{",
      "    public static class PairsTable", "    {",
      "        /// <summary>7 Days item or block name -> the Minecraft item it pairs with (1 to 1).</summary>",
      "        public static readonly Dictionary<string, string> ToMinecraft = new Dictionary<string, string>", "        {"]
for p in pairs:
    pc.append("            { \"%s\", \"%s\" },   // %s" % (p["id_7days"], p["id_minecraft"], p["relation"]))
pc += ["        };", "    }", "}", ""]
open(os.path.join(ROOT, "src", "Generated", "PairsTable.cs"), "w", encoding="utf-8").write("\n".join(pc))
print("pairs:", len(pairs))

# ---- armor.json + pairs.json -> src/Generated/ArmorTable.cs (7 Days armour id -> Minecraft armour points) ----
armor = {r["id_minecraft"]: r["points"] for r in json.load(open(os.path.join(ROOT, "sheets", "armor.json"), encoding="utf-8"))["rows"]}
ac = ["// GENERATED by tools/build_config.py from sheets/armor.json + sheets/pairs.json. Do not edit by hand.",
      "using System.Collections.Generic;", "", "namespace SteveDaysToDie.Generated", "{",
      "    public static class ArmorTable", "    {",
      "        /// <summary>7 Days armour piece -> armour points of its Minecraft pair (1 point = half an armour icon).</summary>",
      "        public static readonly Dictionary<string, int> Points = new Dictionary<string, int>", "        {"]
n_armor = 0
for p in pairs:
    if p["id_minecraft"] in armor:
        ac.append("            { \"%s\", %d },   // %s" % (p["id_7days"], armor[p["id_minecraft"]], p["id_minecraft"]))
        n_armor += 1
ac += ["        };", "    }", "}", ""]
open(os.path.join(ROOT, "src", "Generated", "ArmorTable.cs"), "w", encoding="utf-8").write("\n".join(ac))
print("armour pieces with points:", n_armor)

print("melee items with a Minecraft rhythm:", len(result))
for name, speed, why in result:
    print("  %-36s %-22s %.2f/s  recarga %.2fs" % (name, why, speed, 1.0 / speed))
