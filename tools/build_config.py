_tagcache = {}
def _tag(name):
    name = name.replace("minecraft:", "")
    if name in _tagcache: return _tagcache[name]
    out = set(); _tagcache[name] = out
    t = _j("data/minecraft/tags/item/%s.json" % name) or _j("data/minecraft/tags/items/%s.json" % name)
    for v in (t or {}).get("values", []):
        v = v["id"] if isinstance(v, dict) else v
        out.update(_tag(v[1:]) if v.startswith("#") else {v.replace("minecraft:", "")})
    return out
def _ing(t):
    s = set()
    if t is None: return s
    if isinstance(t, list):
        for x in t: s |= _ing(x)
    elif isinstance(t, dict):
        if "item" in t: s.add(t["item"].replace("minecraft:", ""))
        if "tag" in t: s |= _tag(t["tag"])
    elif isinstance(t, str):
        s |= _tag(t[1:]) if t.startswith("#") else {t.replace("minecraft:", "")}
    return s
