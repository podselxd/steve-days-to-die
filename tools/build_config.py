"""Generates, from sheets/combat.json: the 7 Days XML patch with Minecraft swing rates
(SteveDaysToDie/Config/items.xml) and the code table (src/Generated/CombatTable.cs).
Covers EVERY melee item a player can hold: exact rows first, then the class rules."""
import json, os, re
from gamedata import ROOT, SevenDays

sheet = json.load(open(os.path.join(ROOT, "sheets", "combat.json"), encoding="utf-8"))
exact = {r["id_7days"]: r["attack_speed"] for r in sheet["rows"]}
classes = [(re.compile(c["match"]), c) for c in sheet["classes"]]
sd = SevenDays()


def action0(name):
    for n in sd.chain(name):
        for p in n.findall("property"):
            if p.get("class") == "Action0":
                for q in p.findall("property"):
                    if q.get("name") == "Class":
                        return q.get("value")
    return None


def player_melee():
    for name in sorted(sd.items):
        node = sd.items[name]
        if node.tag != "item" or name.endswith("Master") or name.endswith("Admin") or name.startswith("admin"):
            continue
        if name.startswith("meleeHand") and name != "meleeHandPlayer":
            continue   # animals' and zombies' attacks
        if action0(name) in ("Melee", "DynamicMelee"):
            yield name


for r in sheet["rows"]:
    if r["id_7days"] not in sd.items:
        raise SystemExit("combat.json: %s no existe en items.xml" % r["id_7days"])

result, unmatched = [], []
for name in player_melee():
    if name in exact:
        result.append((name, exact[name], "par exacto"))
        continue
    cls = next((c for rx, c in classes if rx.search(name)), None)
    if cls is None:
        unmatched.append(name)
    else:
        result.append((name, cls["attack_speed"], cls["class"]))
if unmatched:
    raise SystemExit("combat.json: sin ritmo (agrega una clase): " + ", ".join(unmatched))

xml = ["<configs>", "    <!-- GENERATED by tools/build_config.py from sheets/combat.json: Minecraft swing rates. -->"]
cs = ["// GENERATED by tools/build_config.py from sheets/combat.json. Do not edit by hand.",
      "using System.Collections.Generic;", "", "namespace SteveDaysToDie.Generated", "{",
      "    public static class CombatTable", "    {",
      "        /// <summary>7 Days item name -> seconds for the attack bar to refill (1 / Minecraft attack speed).</summary>",
      "        public static readonly Dictionary<string, float> Cooldown = new Dictionary<string, float>", "        {"]
for name, speed, why in result:
    apm = int(round(speed * 60))
    node = sd.items[name]
    if any(pe.get("name") == "AttacksPerMinute" for pe in node.iter("passive_effect")):
        xml.append("    <set xpath=\"/items/item[@name='%s']/effect_group/passive_effect[@name='AttacksPerMinute']/@value\">%d</set>"
                   % (name, apm))
    else:
        xml.append("    <append xpath=\"/items/item[@name='%s']\"><effect_group name=\"svd_mc_speed\">"
                   "<passive_effect name=\"AttacksPerMinute\" operation=\"base_set\" value=\"%d\"/></effect_group></append>"
                   % (name, apm))
    cs.append("            { \"%s\", %sf },   // %s, %s/s" % (name, round(1.0 / speed, 3), why, speed))
xml.append("</configs>")
cs += ["        };", "    }", "}", ""]
open(os.path.join(ROOT, "SteveDaysToDie", "Config", "items.xml"), "w", encoding="utf-8").write("\n".join(xml) + "\n")
os.makedirs(os.path.join(ROOT, "src", "Generated"), exist_ok=True)
open(os.path.join(ROOT, "src", "Generated", "CombatTable.cs"), "w", encoding="utf-8").write("\n".join(cs))
