    res = r.get("result"); rid = res.get("id") or res.get("item") if isinstance(res, dict) else res
    if rid: _mcids.add(rid.replace("minecraft:", ""))
    for v in (r.get("key") or {}).values(): _mcids |= _ing(v)
    for v in r.get("ingredients") or []: _mcids |= _ing(v)
    if "ingredient" in r: _mcids |= _ing(r["ingredient"])
