bbj = json.load(open(os.path.join(ROOT, "sheets", "blocked_buffs.json"), encoding="utf-8"))
bb, groups = bbj["rows"], bbj["groups"]
gnames = [g["group"] for g in groups]
for r in bb:
    if r["id_7days_buff"] not in sd.buffs:
        raise SystemExit("blocked_buffs.json: %s no existe en buffs.xml" % r["id_7days_buff"])
    if r["group"] not in gnames:
        raise SystemExit("blocked_buffs.json: grupo %s no esta en groups" % r["group"])
