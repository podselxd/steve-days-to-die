"""Minecraft mob models straight from the player's Minecraft 26.2 jar (user 2026-11-13: "que los mobs tengan sus
texturas 3d"): extracts the model classes, reads each createBodyLayer with tools/mc_model_reader.py (needs the JDK's
javap) and writes src/Generated/McModelsTable.cs, which src/Mobs/McAnimal.cs builds the boxes from.
Run by hand when the list changes:  python tools/gen_mc_models.py"""
import os, sys, zipfile, json, math, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JAR = os.path.join(os.environ.get("APPDATA", ""), ".minecraft", "versions", "26.2", "26.2.jar")
M = "net/minecraft/client/model/"
# mob id -> (model class, method). Texture size comes from the model (LayerDefinition.create) or "tex" below.
MODELS = {
    "skeleton": (M + "monster/skeleton/SkeletonModel", "createBodyLayer"),
    "spider": (M + "monster/spider/SpiderModel", "createSpiderBodyLayer"),
    "wolf": (M + "animal/wolf/AdultWolfModel", "createBodyLayer"),
    "rabbit": (M + "animal/rabbit/AdultRabbitModel", "createBodyLayer"),
    "fox": (M + "animal/fox/AdultFoxModel", "createBodyLayer"),
    "goat": (M + "animal/goat/GoatModel", "createBodyLayer"),
    "bat": (M + "ambient/BatModel", "createBodyLayer"),
    "witch": (M + "monster/witch/WitchModel", "createBodyLayer"),
    "iron_golem": (M + "animal/golem/IronGolemModel", "createBodyLayer"),
    "snow_golem": (M + "animal/golem/SnowGolemModel", "createBodyLayer"),
    "villager": (M + "npc/VillagerModel", "createBodyModel"),
    "cat": (M + "animal/feline/AdultFelineModel", "createBodyMesh"),
    "parrot": (M + "animal/parrot/ParrotModel", "createBodyLayer"),
    "bee": (M + "animal/bee/AdultBeeModel", "createBodyLayer"),
    "polar_bear": (M + "animal/polarbear/PolarBearModel", "createBodyLayer"),
    "panda": (M + "animal/panda/PandaModel", "createBodyLayer"),
    "llama": (M + "animal/llama/LlamaModel", "createBodyLayer"),
    "horse": (M + "animal/equine/AbstractEquineModel", "createBodyMesh"),
    "frog": (M + "animal/frog/FrogModel", "createBodyLayer"),
    "armadillo": (M + "animal/armadillo/AdultArmadilloModel", "createBodyLayer"),
    "camel": (M + "animal/camel/AdultCamelModel", "createBodyLayer"),
    "allay": (M + "animal/allay/AllayModel", "createBodyLayer"),
    "hoglin": (M + "monster/hoglin/HoglinModel", "createBodyLayer"),
    "piglin": (M + "monster/piglin/AdultPiglinModel", "createBodyLayer"),
    "blaze": (M + "monster/blaze/BlazeModel", "createBodyLayer"),
    "ghast": (M + "monster/ghast/GhastModel", "createBodyLayer"),
    "illager": (M + "monster/illager/IllagerModel", "createBodyLayer"),
    "magma_cube": (M + "monster/slime/MagmaCubeModel", "createBodyLayer"),
    "sniffer": (M + "animal/sniffer/SnifferModel", "createBodyLayer"),
    "turtle": (M + "animal/turtle/AdultTurtleModel", "createBodyLayer"),
    "axolotl": (M + "animal/axolotl/AdultAxolotlModel", "createBodyLayer"),
}
TEX = {"wolf": (64, 32), "villager": (64, 64), "cat": (64, 32), "horse": (64, 64)}
# parts the renderer hides in Minecraft (overlays drawn by other layers, saddles, baby-only parts...)
SKIP = {"hat", "hat_rim", "jacket", "left_sleeve", "right_sleeve", "left_pants", "right_pants", "saddle", "bridle",
        "left_saddle_mouth", "right_saddle_mouth", "left_saddle_line", "right_saddle_line", "head_saddle", "mouth_saddle_wrap",
        "left_chest", "right_chest", "cloak", "ear"}
KEEP_HAT = {"witch"}   # the witch's "hat" is her real hat (villagers and illagers hide theirs)
SKIP_BY = {"illager": {"arms", "left_shoulder"}, "turtle": {"egg_belly"}, "frog": {"croaking_body", "tongue"}, "armadillo": {"cube"}}


def main():
    tmp = os.path.join(tempfile.gettempdir(), "svd_mcmodels")
    z = zipfile.ZipFile(JAR)
    for n in z.namelist():
        if n.startswith(M) and n.endswith(".class") and not os.path.exists(os.path.join(tmp, n)):
            z.extract(n, tmp)
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import mc_model_reader as R
    R.BASE = tmp
    out = ["// GENERATED by tools/gen_mc_models.py from the Minecraft 26.2 jar's model code. Do not edit by hand.",
           "// One line per part: name;parent index;pivot x,y,z;rotation x,y,z (degrees);boxes u,v,x,y,z,w,h,d,grow,mirror|...",
           "namespace SteveDaysToDie.Generated", "{", "    public static class McModelsTable", "    {",
           "        public static readonly System.Collections.Generic.Dictionary<string, (int tw, int th, string parts)> Models = new System.Collections.Generic.Dictionary<string, (int, int, string)>",
           "        {"]
    for mid, (cls, meth) in MODELS.items():
        m = R.model(cls, meth, [("def", 0.0)])
        if not m:
            print("NO MODEL", mid); continue
        tw, th = m["tex"] or TEX.get(mid, (64, 32))
        lines = []

        def walk(p, parent):
            nm = p["name"]
            if (nm in SKIP and not (nm == "hat" and mid in KEEP_HAT)) or nm in SKIP_BY.get(mid, ()): return
            idx = len(lines)
            x, y, z, rx, ry, rz = [float(v or 0) for v in p["pose"]]
            boxes = "|".join("%d,%d,%g,%g,%g,%g,%g,%g,%g,%d" % (c["u"], c["v"], *[round(b, 4) for b in c["box"]], round(c["inflate"], 4), 1 if c["mirror"] else 0) for c in p["cubes"])
            lines.append("%s;%d;%g,%g,%g;%g,%g,%g;%s" % (nm, parent, round(x, 4), round(y, 4), round(z, 4),
                         round(math.degrees(rx), 3), round(math.degrees(ry), 3), round(math.degrees(rz), 3), boxes))
            for k in p["kids"]: walk(k, idx)
        for k in m["root"]["kids"]: walk(k, -1)
        out.append('            ["%s"] = (%d, %d, "%s"),' % (mid, tw, th, "\\n".join(lines)))
        print(mid, tw, th, len(lines), "parts", m["warn"] or "")
    out += ["        };", "    }", "}", ""]
    open(os.path.join(ROOT, "src", "Generated", "McModelsTable.cs"), "w", encoding="utf-8").write("\n".join(out))


if __name__ == "__main__":
    main()
